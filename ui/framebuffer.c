void framebuffer_rect(Framebuffer *fb, U32 x, U32 y, U32 w, U32 h, U32 rgb) {
    U32 dx, dy, pixel;
    if (x >= fb->width || y >= fb->height) return;
    if (w > fb->width - x) w = fb->width - x;
    if (h > fb->height - y) h = fb->height - y;
    pixel = fb->format == 1 ? rgb : ((rgb & 255) << 16) | (rgb & 0xff00) | ((rgb >> 16) & 255);
    for (dy = 0; dy < h; ++dy)
        for (dx = 0; dx < w; ++dx)
            fb->pixels[(U64)(y + dy) * fb->stride + x + dx] = pixel;
}

